#[test]
fn matches_python_partitioning() {
    for &a in ADDRESSES {
        for n in [2u32, 3, 5] {
            for i in 1..=n {
                let expect = IN.contains(&(a, i, n));
                assert_eq!(in_local_partition(a, (i, n)), expect, "{a:06x} {i}/{n}");
            }
        }
        assert!(in_local_partition(a, (1, 1)));
    }
}
